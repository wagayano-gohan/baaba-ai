/** buildSystemPrompt のオプション。 */
export interface BuildSystemPromptOptions {
  /** 呼びかけに使うご本人のお名前（不明なら省略・null可）。 */
  profileName?: string | null
  /**
   * ご本人の住所（profiles.address）。「近くの病院」等の検索の基準地点として使う。
   * 未登録ならnull。その場合はAIが必要に応じて場所を尋ねる。
   */
  address?: string | null
}

/** 日本時間の今日の日付を「YYYY年M月D日（曜）」形式で返す。 */
function todayLabelJST(): string {
  return new Intl.DateTimeFormat('ja-JP', {
    timeZone: 'Asia/Tokyo',
    year: 'numeric',
    month: 'long',
    day: 'numeric',
    weekday: 'short',
  }).format(new Date())
}

/**
 * 実際に送信するシステムプロンプトを組み立てる。
 * 基本方針に加えて、今日の日付（日本時間）と、分かっていれば呼びかけ名を添える。
 */
export function buildSystemPrompt(options?: BuildSystemPromptOptions): string {
  const lines = [BABA_AI_SYSTEM_PROMPT, '', `本日は ${todayLabelJST()}（日本時間）です。`]

  const name = options?.profileName?.trim()
  if (name) {
    lines.push(`利用者のお名前は「${name}」さんです。必要に応じてお名前で呼びかけてください。`)
  }

  // 住所が登録されていれば「近くの〜」の基準地点として使う。
  // 未登録の場合は何も添えない（AIが必要に応じて場所を尋ねる想定）。
  const address = options?.address?.trim()
  if (address) {
    lines.push(
      `利用者のご住所は「${address}」です。「近くの」「この辺で」と言われた場合は、この住所を基準に検索してください。`,
    )
  } else {
    lines.push(
      'ご住所は未登録です。「近くの」と言われて場所が特定できない場合は、どのあたりでお探しか1つだけ尋ねてください。',
    )
  }

  return lines.join('\n')
}
